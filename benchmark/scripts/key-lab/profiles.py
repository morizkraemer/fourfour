def zprofile(name):
    p = np.array(PROFILES[name], dtype=np.float64)
    p = p - p.mean(axis=1, keepdims=True)
    return p / np.linalg.norm(p, axis=1, keepdims=True)


def harmonic(name, decay=0.6, n=4):
    p = np.array(PROFILES[name], dtype=np.float64)
    out = np.zeros_like(p)
    for h in range(1, n + 1):
        shift = int(round(12 * np.log2(h))) % 12
        out += decay ** (h - 1) * np.roll(p, shift, axis=1)
    out = out - out.mean(axis=1, keepdims=True)
    return out / np.linalg.norm(out, axis=1, keepdims=True)


def templates(name, band_weights=(1.0, 1.0, 1.0), decay=0.0, n=1):
    z = harmonic(name, decay, n) if n > 1 else zprofile(name)
    return np.stack([np.concatenate([w * z[m] for w in band_weights]) for m in range(2)])
